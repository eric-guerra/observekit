'use strict';
// node slo/generate.js → deploy/prometheus/slo-rules.yml + deploy/grafana/dashboards/slo-<service>.json
const fs = require('fs');
const path = require('path');
const { rulesFor, toYaml } = require('./burnrate');

function dashboard(service, slos) {
  let id = 1;
  const panel = (title, targets, type, gridPos, extra = {}) => ({ id: id++, title, type, gridPos, datasource: 'Prometheus', targets, ...extra });
  const panels = [
    panel('Request rate', [{ expr: `sum by (route) (rate(http_server_requests_total{service="${service}"}[5m]))`, legendFormat: '{{route}}' }], 'timeseries', { x: 0, y: 0, w: 8, h: 8 }),
    panel('Error ratio (5xx)', [{ expr: `sum(rate(http_server_requests_total{service="${service}",status_class="5xx"}[5m])) / sum(rate(http_server_requests_total{service="${service}"}[5m]))` }], 'timeseries', { x: 8, y: 0, w: 8, h: 8 }, { fieldConfig: { defaults: { unit: 'percentunit' } } }),
    panel('Latency p50 / p95 / p99', ['0.5', '0.95', '0.99'].map((q) => ({
      expr: `histogram_quantile(${q}, sum by (le) (rate(http_server_duration_seconds_bucket{service="${service}"}[5m])))`, legendFormat: `p${Math.round(q * 100)}`,
    })), 'timeseries', { x: 16, y: 0, w: 8, h: 8 }, { fieldConfig: { defaults: { unit: 's' } } }),
  ];
  slos.forEach((s, i) => {
    panels.push(panel(`${s.name}: error budget remaining (30d)`, [{
      expr: `1 - (avg_over_time(slo:${s.name}:error_ratio_1h[30d]) / ${+(1 - s.objective).toPrecision(6)})`,
    }], 'stat', { x: (i % 3) * 8, y: 8, w: 8, h: 5 }, {
      fieldConfig: { defaults: { unit: 'percentunit', thresholds: { mode: 'absolute', steps: [{ color: 'red', value: null }, { color: 'orange', value: 0.25 }, { color: 'green', value: 0.5 }] } } },
    }));
  });
  return {
    uid: `slo-${service}`,
    title: `${service} — RED + SLOs`,
    schemaVersion: 36,
    time: { from: 'now-6h', to: 'now' },
    tags: ['generated', 'slo'],
    panels,
  };
}

function main() {
  const slos = JSON.parse(fs.readFileSync(path.join(__dirname, 'slos.json'), 'utf8'));
  const groups = slos.map((s) => {
    const { recording, alerts } = rulesFor(s);
    return { name: `slo-${s.name}`, rules: [...recording, ...alerts] };
  });
  const rulesPath = path.join(__dirname, '..', 'deploy', 'prometheus', 'slo-rules.yml');
  fs.mkdirSync(path.dirname(rulesPath), { recursive: true });
  fs.writeFileSync(rulesPath, '# GENERATED by slo/generate.js — edit slo/slos.json instead\n' + toYaml(groups));

  const byService = {};
  for (const s of slos) (byService[s.service] = byService[s.service] || []).push(s);
  const dashDir = path.join(__dirname, '..', 'deploy', 'grafana', 'dashboards');
  fs.mkdirSync(dashDir, { recursive: true });
  for (const [svc, list] of Object.entries(byService)) {
    fs.writeFileSync(path.join(dashDir, `slo-${svc}.json`), JSON.stringify(dashboard(svc, list), null, 2) + '\n');
  }
  console.log(`wrote ${rulesPath} and ${Object.keys(byService).length} dashboards`);
}

module.exports = { dashboard };
if (require.main === module) main();
